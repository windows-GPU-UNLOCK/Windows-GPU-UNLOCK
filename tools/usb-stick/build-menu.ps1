# Build the GPU-UNLOCK USB boot menu (menu.c) against this checkout's current builds.
#   default     normal menu: pins the headless USB wrapper (item 1) and the generic probe (item 2)
#   -ProbeOnly  dump-phase menu: pins only the probe; item 1 is shown as not ready
# The pins are size + SHA-256, so rebuild the menu whenever the wrapper or probe is rebuilt.
# Builds files only (tools/usb-stick/build).
param([Parameter(Mandatory)][string]$Clang,[Parameter(Mandatory)][string]$LldLink,[Parameter(Mandatory)][string]$Python,
      [ValidateRange(1,99)][int]$TimeoutSeconds=20,[ValidateRange(1,3)][int]$DefaultItem=1,[switch]$ProbeOnly)
$ErrorActionPreference='Stop'
$here=$PSScriptRoot
$repo=[IO.Path]::GetFullPath((Join-Path $here '..\..'))
$boot=Join-Path $repo 'internal-boot\boot'
$unlock=Join-Path $repo 'internal-boot\unlock'
$edk=Join-Path $repo 'deps\edk2\MdePkg\Include'
$wrapper=Join-Path $boot 'build\headless\HEADLESS.EFI'
$probe=Join-Path $boot 'build\probe-generic\BOOTX64.EFI'
function Sha([string]$p){(Get-FileHash -LiteralPath $p -Algorithm SHA256).Hash.ToLowerInvariant()}
. (Join-Path $repo 'research\profile\probe-manifest.ps1')
if(!(Test-Path -LiteralPath $probe)){throw "Missing $probe; run make-stick.ps1 first"}
$probeManifest=Get-Content -LiteralPath (Join-Path $boot 'build\probe-generic\manifest.json') -Raw | ConvertFrom-Json
Assert-GuGenericProbeManifest $repo $probeManifest $probe
if((Get-Content -LiteralPath (Join-Path $boot 'platform-config.h') -TotalCount 1) -notmatch 'build-usb\.ps1'){throw 'platform-config.h is not the USB configuration'}
if($ProbeOnly){
 if($DefaultItem -eq 1){$DefaultItem=3}
 $profileName='(dump phase)';$unlockRow=$null
} else {
 if(!(Test-Path -LiteralPath $wrapper)){throw "Missing $wrapper; the unlock package is not built yet (use -ProbeOnly)"}
 $usbManifest=Get-Content -LiteralPath (Join-Path $boot 'build\headless\usb-manifest.json') -Raw | ConvertFrom-Json
 if((Sha $wrapper) -ne $usbManifest.EfiSha256){throw 'HEADLESS.EFI does not match usb-manifest.json'}
 if($usbManifest.CanUnlock -ne $true -or $usbManifest.Mode -ne 'single-rtx-headless-unlock-then-windows-usb'){throw 'usb-manifest.json is not the headless USB unlock build'}
 $profileName=[string]$usbManifest.HardwareProfile
 if($profileName -notmatch '^[A-Za-z0-9-]{1,60}$'){throw 'Unexpected profile name in usb-manifest.json'}
 $unlockRow=[ordered]@{Source=$wrapper;Sha256=(Sha $wrapper);Bytes=(Get-Item $wrapper).Length;Target='EFI\GPU-UNLOCK\UNLOCK.EFI'}
}
$out=Join-Path $here 'build'
New-Item -ItemType Directory -Force $out | Out-Null
$config=@(
 '/* Generated by tools/usb-stick/build-menu.ps1. */',
 ('#define MENU_HAS_UNLOCK {0}' -f $(if($ProbeOnly){0}else{1})),
 ('#define MENU_PROFILE_NAME L"{0}"' -f $profileName),
 ('#define MENU_TIMEOUT_SECONDS {0}U' -f $TimeoutSeconds),
 ('#define MENU_DEFAULT_ITEM {0}U' -f $DefaultItem),
 ('#define MENU_PROBE_SHA256 "{0}"' -f (Sha $probe)),
 ('#define MENU_PROBE_BYTES {0}U' -f (Get-Item $probe).Length)
)
if($unlockRow){$config+=@(('#define MENU_UNLOCK_SHA256 "{0}"' -f $unlockRow.Sha256),('#define MENU_UNLOCK_BYTES {0}U' -f $unlockRow.Bytes))}
$config | Set-Content -LiteralPath (Join-Path $out 'menu-config.h') -Encoding ascii
$objects=@()
foreach($src in @((Join-Path $here 'menu.c'),(Join-Path $unlock 'sha256.c'),(Join-Path $repo 'internal-boot\efi_runtime.c'))) {
 $obj=Join-Path $out ([IO.Path]::GetFileNameWithoutExtension($src)+'.obj')
 & $Clang -target x86_64-pc-windows-msvc -std=c11 -ffreestanding -fno-builtin -fno-stack-protector -mno-red-zone -fshort-wchar -Os -Wall -Wextra -Werror `
   -I $out -I $boot -I $unlock -I $edk -I (Join-Path $edk 'X64') -c $src -o $obj
 if($LASTEXITCODE -ne 0){throw "Compile failed: $src"}
 $objects+=$obj
}
$efi=Join-Path $out 'MENU.EFI'
& $LldLink /nologo /nodefaultlib /subsystem:efi_application /entry:efi_main /machine:x64 /base:0 /dynamicbase /nxcompat /timestamp:0 /opt:ref /opt:icf "/map:$out\MENU.map" "/out:$efi" @objects
if($LASTEXITCODE -ne 0){throw 'Menu link failed'}
& $Python -I (Join-Path $unlock 'verify_pe.py') $efi "$out\MENU.map" --output "$out\pe-verification.json" | Out-Null
if($LASTEXITCODE -ne 0){throw 'Menu PE verification failed'}
[ordered]@{Mode=$(if($ProbeOnly){'dump-phase'}else{'unlock'});Menu=(Sha $efi);MenuBytes=(Get-Item $efi).Length;Profile=$profileName
 TimeoutSeconds=$TimeoutSeconds;DefaultItem=$DefaultItem;Unlock=$unlockRow
 Probe=[ordered]@{Source=$probe;Sha256=(Sha $probe);Bytes=(Get-Item $probe).Length;Target='EFI\GPU-UNLOCK\PROBE.EFI'}
 BuiltUtc=[DateTime]::UtcNow.ToString('o')} | ConvertTo-Json -Depth 3 | Set-Content -LiteralPath (Join-Path $out 'menu-manifest.json') -Encoding utf8
"Built $(if($ProbeOnly){'dump-phase'}else{'unlock'}) menu $efi ($profileName, item $DefaultItem after $TimeoutSeconds s)."
